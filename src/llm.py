def generate_codebase_answer(
    query: str,
    results: List[SearchResult],
    groq_client: Optional[Any] = None,
    gemini_client: Optional[Any] = None,
    groq_primary_model: Optional[str] = None,
    groq_fallback_models: Optional[List[str]] = None,
    enable_gemini_fallback: Optional[bool] = None,
    gemini_model: Optional[str] = None,
    groq_api_key: Optional[str] = None,
    gemini_api_key: Optional[str] = None,
    system_instruction: str = REPOSITORY_ASSISTANT_SYSTEM_INSTRUCTION,
    max_output_tokens: int = 2048,
    temperature: float = 0.2,
    timeout: float = 30.0,
    on_status: Optional[StatusCallback] = None,
    # Backward compatibility arguments
    client: Optional[Any] = None,
    model: Optional[str] = None,
    api_key: Optional[str] = None,
) -> RAGResponse:
    """Executes the multi-provider RAG generation pipeline for a user question and retrieved chunks.

    Applies application-level safeguards before contacting any LLM provider:
      - Validates non-empty query.
      - If no chunks were retrieved, returns a safe explanation without calling any provider.
      - Enforces context and output size limits.
      - Executes Groq primary model, then Groq fallback models, and finally optional Gemini fallback.
      - Sanitizes error messages to protect credentials.

    Args:
        query: User question about the codebase.
        results: Retrieved SearchResult objects from TFIDFRetriever.
        groq_client: Optional pre-configured Groq client (useful for testing).
        gemini_client: Optional pre-configured Gemini client (useful for testing).
        groq_primary_model: Model name for primary Groq attempt.
        groq_fallback_models: Sequence of model names for Groq fallback attempts.
        enable_gemini_fallback: Boolean flag to enable/disable Gemini backup.
        gemini_model: Model name for Gemini backup attempt.
        groq_api_key: Optional explicit Groq API key string.
        gemini_api_key: Optional explicit Gemini API key string.
        system_instruction: System prompt to enforce repository-only policy.
        max_output_tokens: Maximum tokens allowed for the generated answer.
        temperature: Sampling temperature (default 0.2 for factual code explanation).
        timeout: Network timeout per request in seconds.
        on_status: Optional callback function receiving live progress strings.
        client: Legacy argument; routes to Gemini or Groq depending on client capabilities.
        model: Legacy model name override.
        api_key: Legacy API key override.

    Returns:
        RAGResponse containing the answer, sources, provider, and model used.

    Raises:
        ValueError: If query is empty.
        MissingAPIKeyError: If required credentials are missing.
        AllProvidersFailedError: If all primary and fallback attempts fail.
        GroqAPIError / GeminiAPIError: If a specific fatal provider error occurs.
        EmptyResponseError: If the model returns an empty response.
    """
    if not query or not query.strip():
        raise ValueError("User question cannot be empty.")

    # Application safeguard: do not call any LLM if no relevant chunks exist
    if not results:
        target_model = groq_primary_model or os.getenv("GROQ_PRIMARY_MODEL", DEFAULT_GROQ_PRIMARY_MODEL)
        return RAGResponse(
            answer=(
                "No relevant code snippets were found in the uploaded repository for your question. "
                "Please verify that your question relates to the indexed codebase files."
            ),
            sources=[],
            provider="Local",
            model=target_model,
            is_fallback=True,
        )

    # Legacy support: if client is explicitly provided as a Gemini client or model is a Gemini model
    if client is not None:
        if hasattr(client, "models") or (model and "gemini" in model.lower()):
            from src.llm_providers import call_gemini_model
            target_gem_model = model or gemini_model or DEFAULT_GEMINI_MODEL
            prompt = build_rag_prompt(query=query, results=results)
            answer = call_gemini_model(
                client=client,
                model=target_gem_model,
                prompt=prompt,
                system_instruction=system_instruction,
                max_output_tokens=max_output_tokens,
                temperature=temperature,
            )
            return RAGResponse(
                answer=answer,
                sources=list(results),
                provider="Gemini",
                model=target_gem_model,
                is_fallback=False,
            )
        elif hasattr(client, "chat"):
            groq_client = client

    from src.llm_providers import execute_multi_provider_fallback

    return execute_multi_provider_fallback(
        query=query,
        results=results,
        groq_client=groq_client,
        gemini_client=gemini_client,
        groq_primary_model=groq_primary_model or (model if (model and "gemini" not in model.lower()) else None),
        groq_fallback_models=groq_fallback_models,
        enable_gemini_fallback=enable_gemini_fallback,
        gemini_model=gemini_model or (model if (model and "gemini" in model.lower()) else None),
        groq_api_key=groq_api_key or (api_key if not gemini_api_key else None),
        gemini_api_key=gemini_api_key,
        system_instruction=system_instruction,
        max_output_tokens=max_output_tokens,
        temperature=temperature,
        timeout=timeout,
        on_status=on_status,
    )
